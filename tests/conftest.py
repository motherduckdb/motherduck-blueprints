from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from e2e_support import Cli, FakeMotherDuck


@pytest.fixture
def fake_motherduck(tmp_path: Path) -> FakeMotherDuck:
    return FakeMotherDuck(tmp_path / "fake-motherduck")


@pytest.fixture
def md_cli(tmp_path: Path, fake_motherduck: FakeMotherDuck) -> Cli:
    return Cli(tmp_path, fake_motherduck)


@pytest.fixture(scope="session")
def starter_template(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """One `md-blueprints init` per session; each test gets its own copy."""
    base = tmp_path_factory.mktemp("starter")
    root = base / "repo"
    Cli(base, FakeMotherDuck(base / "fake-motherduck")).ok("init", str(root))
    return root


@pytest.fixture
def starter(tmp_path: Path, starter_template: Path) -> Path:
    """A customer repository generated by `md-blueprints init`, as the README tells customers to do."""
    root = tmp_path / "repo"
    shutil.copytree(starter_template, root, symlinks=True)
    return root
